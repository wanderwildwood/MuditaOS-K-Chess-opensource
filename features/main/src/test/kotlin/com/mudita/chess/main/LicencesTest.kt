package com.mudita.chess.main

import com.google.common.truth.Truth.assertThat
import com.mudita.chess.ui.LicenceText
import com.mudita.chess.ui.LicencesData
import com.mudita.chess.ui.licenceComponentsFromJson
import com.mudita.chess.ui.licenceParagraphs
import com.mudita.chess.ui.licencesProblems
import java.io.File
import java.net.URI
import org.junit.jupiter.api.Test

/**
 * The Licenses page's data as the build made it: the AboutLibraries plugin in app-android writes
 * app-android/build/generated/aboutLibraries/<variant>/res/raw/aboutlibraries.json (this module's
 * unit tests depend on that task, see build.gradle.kts). The release list is read when there is one.
 */
class LicencesTest {

    private fun raw(name: String) = File("src/main/res/raw/$name.txt").readText()

    private val json: File? = File("../../app-android/build/generated/aboutLibraries").walkTopDown()
        .filter { it.name == "aboutlibraries.json" }
        .sortedBy { if ("release" in it.path) 0 else 1 }
        .firstOrNull()

    private val generated by lazy { licenceComponentsFromJson(json!!.readText()) }

    private val data by lazy {
        LicencesData(
            "Chess+", SOURCE_URL, "GPL-3.0-only", generated,
            LICENCE_RAW.map { LicenceText(it.first, it.first, it.second) },
        )
    }

    /** What must be on the page whatever else changes: group:artifact, or a config/libraries name. */
    private val expected = listOf(
        "com.mudita:MMD",
        "com.github.bhlangonijr:chesslib",
        "io.insert-koin:koin-core",
        "org.jetbrains.kotlin:kotlin-stdlib",
        "com.squareup.okio:okio",
        "Mudita's Chess (the app this began as)",
        "Fairy-Stockfish 14",
        "Lato typeface",
        "Java library desugaring (desugar_jdk_libs)",
    )

    @Test
    fun `the build listed the libraries`() {
        assertThat(json).isNotNull()
        assertThat(generated.size).isAtLeast(5)
    }

    @Test
    fun `the licence data has no problems`() {
        assertThat(licencesProblems(data)).isEmpty()
    }

    @Test
    fun `every expected component is listed`() {
        val missing = expected.filterNot { id -> generated.any { it.note?.startsWith("$id ") == true || it.name == id } }
        assertThat(missing).isEmpty()
    }

    @Test
    fun `mmd is shown as mudita`() {
        assertThat(generated.single { it.note?.startsWith("com.mudita:MMD ") == true }.author).isEqualTo("Mudita")
    }

    @Test
    fun `the source link is the apps repository on github`() {
        val uri = URI(SOURCE_URL)
        assertThat(uri.host).isEqualTo("github.com")
        assertThat(uri.path).isEqualTo("/wanderwildwood/MuditaOS-K-Chess-opensource")
    }

    @Test
    fun `the three bundled licence texts split into paragraphs`() {
        assertThat(licenceParagraphs(raw("gpl_3_0")).size).isGreaterThan(10)
        assertThat(licenceParagraphs(raw("apache_2_0")).size).isGreaterThan(10)
        assertThat(licenceParagraphs(raw("ofl_1_1")).size).isGreaterThan(5)
        assertThat(raw("apache_2_0")).contains("Apache License")
    }
}
